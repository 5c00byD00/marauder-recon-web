import { createHash } from "node:crypto";
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export function precacheUrls(root) {
  const urls = new Set(["./", "./index.html"]);
  const walk = (directory) => {
    for (const name of readdirSync(directory)) {
      const path = join(directory, name);
      if (statSync(path).isDirectory()) {
        walk(path);
        continue;
      }
      const url = `./${relative(root, path).split("\\").join("/")}`;
      if (url === "./sw.js") continue;
      urls.add(url);
    }
  };
  walk(root);
  return [...urls].sort();
}

export function renderServiceWorker(urls) {
  const hash = createHash("sha256").update(urls.join("\n")).digest("hex").slice(0, 12);
  return `/* Generated by scripts/write-sw.mjs. Precache URLs are relative to this worker. */
const CACHE = "marauder-recon-${hash}";
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key)))).then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  if (event.request.method !== "GET") return;
  const url = new URL(event.request.url);
  if (url.origin !== self.location.origin) return;
  event.respondWith(load(event.request));
});

async function load(request) {
  const cached = await caches.match(request);
  if (cached) return cached;
  try {
    const response = await fetch(request);
    if (response.ok && response.type === "basic") {
      const cache = await caches.open(CACHE);
      await cache.put(request, response.clone());
    }
    return response;
  } catch (error) {
    if (request.mode === "navigate") {
      const fallback = (await caches.match("./index.html")) || (await caches.match("./"));
      if (fallback) return fallback;
    }
    throw error;
  }
}
`;
}

const isMain = Boolean(process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href);
if (isMain) {
  const root = fileURLToPath(new URL("../dist/", import.meta.url));
  writeFileSync(join(root, "sw.js"), renderServiceWorker(precacheUrls(root)));
}
